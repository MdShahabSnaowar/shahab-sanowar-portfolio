# CONTACT API
# ------------------------------------------------------------
@app.post("/api/contact")
def contact():
    data = request.get_json(silent=True) or {}

    name = str(data.get("name", "")).strip()
    visitor_email = str(data.get("email", "")).strip()
    service = str(data.get("service", "")).strip()
    message = str(data.get("message", "")).strip()

    # Required fields
    missing = [
        field
        for field in REQUIRED_FIELDS
        if not str(data.get(field, "")).strip()
    ]

    if missing:
        return jsonify({
            "ok": False,
            "message": "Please fill all required fields."
        }), 400

    # Length protection
    if (
        len(name) > 120
        or len(visitor_email) > 254
        or len(service) > 120
        or len(message) > 5000
    ):
        return jsonify({
            "ok": False,
            "message": "One or more fields are too long."
        }), 400

    # Basic email validation
    if "@" not in visitor_email or "." not in visitor_email.split("@")[-1]:
        return jsonify({
            "ok": False,
            "message": "Please enter a valid email address."
        }), 400

    submitted_at = datetime.now(timezone.utc).astimezone().strftime(
        "%d %b %Y, %I:%M %p"
    )

    # --------------------------------------------------------
    # OWNER EMAIL
    # --------------------------------------------------------
    owner_subject = f"New Portfolio Contact — {name}"

    owner_text = f"""Hello Shahab,

Someone has contacted you through your portfolio website.

CONTACT DETAILS
----------------
Name: {name}
Email: {visitor_email}
Service Needed: {service}
Submitted: {submitted_at}

MESSAGE
----------------
{message}

You can reply directly to this email to respond to {name}.

— Portfolio Contact System
"""

    owner_html = build_owner_email(
        name=name,
        visitor_email=visitor_email,
        service=service,
        message=message,
        submitted_at=submitted_at,
    )

    # --------------------------------------------------------
    # VISITOR CONFIRMATION EMAIL
    # --------------------------------------------------------
    visitor_subject = "Thank You for Reaching Out — Shahab Sanowar"

    visitor_text = f"""Hi {name},

Thank you for reaching out through my portfolio website.

I've received your message regarding "{service}" and will review the details carefully. I'll get back to you as soon as possible.

I appreciate you taking the time to share your idea with me.

Best regards,
Shahab Sanowar
Backend Developer | Python & Django
"""

    visitor_html = build_visitor_email(
        name=name,
        service=service,
    )

    # --------------------------------------------------------
    # SEND BOTH
    # --------------------------------------------------------
    try:
        # 1. Send enquiry to Shahab
        send_email(
            OWNER_EMAIL,
            owner_subject,
            owner_text,
            owner_html,
            reply_to=visitor_email,
        )

        # 2. Send confirmation to visitor
        send_email(
            visitor_email,
            visitor_subject,
            visitor_text,
            visitor_html,
        )

        return jsonify({
            "ok": True,
            "message": "Message sent successfully. Thank you!"
        })

    except Exception as exc:
        # Keep credentials/internal details out of the browser.
        app.logger.exception(
            "Portfolio contact email failed: %s",
            exc
        )

        return jsonify({
            "ok": False,
            "message": "Unable to send your message right now. Please try again."
        }), 500


