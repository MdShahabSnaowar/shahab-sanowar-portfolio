def send_email(to_email, subject, text_body, html_body, reply_to=None):
    """Send one email through Brevo."""
    if not BREVO_API_KEY or not EMAIL_USERNAME:
        raise RuntimeError(
            "Brevo email configuration is missing"
        )

    payload = {
        "sender": {
            "name": EMAIL_FROM_NAME,
            "email": EMAIL_USERNAME,
        },
        "to": [
            {
                "email": to_email
            }
        ],
        "subject": subject,
        "textContent": text_body,
        "htmlContent": html_body,
    }

    if reply_to:
        payload["replyTo"] = {
            "email": reply_to
        }

    response = requests.post(
        "https://api.brevo.com/v3/smtp/email",
        headers={
            "accept": "application/json",
            "api-key": BREVO_API_KEY,
            "content-type": "application/json",
        },
        json=payload,
        timeout=30,
    )

    if not response.ok:
        raise RuntimeError(
            f"Brevo API error {response.status_code}: "
            f"{response.text[:500]}"
        )

    return response.json() if response.content else {}


